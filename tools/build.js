// Builds the playable pages from game.html:
//   index.html                         installable web app for GitHub Pages (loads backgrounds/*.jpg)
//   sw.js                              its service worker, for offline play
//   <out>/bubble-lagoon-artifact.html  page for the claude.ai artifact, with every background
//                                      inlined as a data URI (the artifact viewer won't load them otherwise)
// Usage: node tools/build.js [artifact-output-dir]
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.join(__dirname, '..');
const game = fs.readFileSync(path.join(root, 'game.html'), 'utf8');
const SITE = 'https://mareearee.github.io/Game1/';
const DESCRIPTION = 'A relaxing bubble-popping puzzle: pop matching bubbles, earn bombs and rainbows, and explore 10 underwater worlds.';

const head = game.slice(0, game.indexOf('</style>') + '</style>'.length);
const body = game.slice(head.length);
const standalone = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="theme-color" content="#05141f">
<meta name="apple-mobile-web-app-title" content="Bubble Lagoon">
<meta name="description" content="${DESCRIPTION}">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<meta property="og:type" content="website">
<meta property="og:title" content="Bubble Lagoon">
<meta property="og:description" content="${DESCRIPTION}">
<meta property="og:url" content="${SITE}">
<meta property="og:image" content="${SITE}og-image.jpg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px);box-sizing:border-box}body{margin:0}[hidden]{display:none!important}</style>
${head}
</head>
<body>
${body.replace(/^\n/, '')}
<script>
if ('serviceWorker' in navigator && location.protocol.startsWith('http')) {
  addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
}
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(root, 'index.html'), standalone);

// Offline support: precache the app shell and every backdrop. The cache name is a hash of what
// it holds, so each new build replaces the old cache. Pages are network-first (updates show up
// right away when online); everything else is cache-first, with Google Fonts cached on first use.
const shell = ['./', 'index.html', 'manifest.webmanifest', 'og-image.jpg',
  ...fs.readdirSync(path.join(root, 'icons')).sort().map(f => 'icons/' + f),
  ...fs.readdirSync(path.join(root, 'backgrounds')).filter(f => f.endsWith('.jpg')).sort().map(f => 'backgrounds/' + f)];
const hash = crypto.createHash('sha256');
for (const f of shell.slice(1)) hash.update(fs.readFileSync(path.join(root, f)));
const version = 'bubble-lagoon-' + hash.digest('hex').slice(0, 12);
fs.writeFileSync(path.join(root, 'sw.js'), `// Generated by tools/build.js. Do not edit by hand.
const CACHE = '${version}';
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('bubble-lagoon-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  const fonts = url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com';
  if (url.origin !== location.origin && !fonts) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(res => {
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put('index.html', copy));
      return res;
    }).catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {
    if (res.ok || res.type === 'opaque') { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  })));
});
`);

const images = fs.readdirSync(path.join(root, 'backgrounds'))
  .filter(f => /^world\d\d\.jpg$/.test(f)).sort()
  .map(f => 'data:image/jpeg;base64,' + fs.readFileSync(path.join(root, 'backgrounds', f)).toString('base64'));
const inline = `<script>window.WORLD_IMAGES = ${JSON.stringify(images)};</script>\n`;
const at = game.indexOf('<script>');
const artifact = game.slice(0, at) + inline + game.slice(at);
const outDir = process.argv[2] || root;
const out = path.join(outDir, 'bubble-lagoon-artifact.html');
fs.writeFileSync(out, artifact);
console.log(`index.html ${Math.round(standalone.length / 1024)} KB; sw.js caches ${shell.length} files as ${version}; ${out} ${Math.round(artifact.length / 1024)} KB with ${images.length} inlined backgrounds`);
